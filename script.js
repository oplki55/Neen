const preserveLocalizedWhitespace = (value, translation) => {
  const leadingWhitespace = value.match(/^\s*/)?.[0] || "";
  const trailingWhitespace = value.match(/\s*$/)?.[0] || "";
  return `${leadingWhitespace}${translation}${trailingWhitespace}`;
};

const getContextualTranslation = (node, language) => {
  const key = normalizeLocalizedText(node.nodeValue);
  for (const context of contextualArabicTranslations) {
    if (!node.parentElement?.closest(context.selector)) continue;
    if (language === "ar" && Object.hasOwn(context.phrases, key)) {
      return context.phrases[key];
    }
    if (language === "en") {
      const english = Object.entries(context.phrases).find(([, arabic]) => arabic === key)?.[0];
      if (english) return english;
    }
  }
  return undefined;
};

const translateTextNode = (node, language) => {
  if (node.parentElement?.closest("[data-language-toggle]")) return;
  const value = node.nodeValue;
  if (!value?.trim()) return;
  const contextualTranslation = getContextualTranslation(node, language);
  const translated = contextualTranslation === undefined
    ? localizeValue(value, language)
    : preserveLocalizedWhitespace(value, contextualTranslation);
  if (translated !== value) node.nodeValue = translated;
};

const translatableAttributes = ["alt", "aria-label", "content", "placeholder", "title"];
const translateElementAttributes = (element, language) => {
  if (element.hasAttribute("data-language-toggle")) return;
  translatableAttributes.forEach((attribute) => {
    if (!element.hasAttribute(attribute)) return;
    const value = element.getAttribute(attribute);
    const translated = localizeValue(value, language);
    if (translated !== value) element.setAttribute(attribute, translated);
  });
};

const translateSubtree = (root, language) => {
  if (root.nodeType === Node.TEXT_NODE) {
    translateTextNode(root, language);
    return;
  }
  if (!(root instanceof Element)) return;

  translateElementAttributes(root, language);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) translateTextNode(walker.currentNode, language);
  root.querySelectorAll("*").forEach((element) => translateElementAttributes(element, language));
};

