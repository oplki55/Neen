(() => {
  const section = document.querySelector("[data-news-ticker-section]");
  if (!(section instanceof HTMLElement)) return;

  const track = section.querySelector("[data-news-ticker-track]");
  const viewport = section.querySelector("[data-news-ticker-viewport]");
  const toggle = section.querySelector("[data-news-submit-toggle]");
  const panel = section.querySelector("[data-news-submit-panel]");
  const form = section.querySelector("[data-news-submit-form]");
  const status = section.querySelector("[data-news-submit-status]");

  const makeItem = (item) => {
    const node = document.createElement("span");
    node.className = "neen-news-ticker-item";
    const sender = document.createElement("strong");
    sender.textContent = `${item.sender_name}:`;
    const message = document.createElement("span");
    message.textContent = item.message;
    node.append(sender, message);
    return node;
  };

  const renderTrack = (messages) => {
    track.replaceChildren();
    if (messages.length === 0) {
      viewport.hidden = false;
      const fallback = [{ sender_name: "NEEN", message: "Welcome to the NEEN Gaming Arena!", source: "System" }];
      for (let copy = 0; copy < 2; copy += 1) {
        const group = document.createElement("div");
        group.className = "neen-news-ticker-group";
        group.setAttribute("aria-hidden", copy === 1 ? "true" : "false");
        fallback.forEach((item) => group.append(makeItem(item)));
        track.append(group);
      }
      return;
    }
    viewport.hidden = false;
    for (let copy = 0; copy < 2; copy += 1) {
      const group = document.createElement("div");
      group.className = "neen-news-ticker-group";
      group.setAttribute("aria-hidden", copy === 1 ? "true" : "false");
      messages.forEach((item) => group.append(makeItem(item)));
      track.append(group);
    }
  };

  const loadTicker = async () => {
    try {
      const response = await fetch("/api/news-ticker", { credentials: "same-origin" });
      const result = await response.json();
      if (!response.ok || result.success !== true) throw new Error("Ticker unavailable");
      const data = result.data;
      const settings = data.settings;
      const defaultColors = {
        background: "#17132f",
        text: "#fff8fc",
        sender: "#f3a3c6",
        separator: "#c8c8ed",
        glow: "#d65f96",
      };
      const isSafeColor = (value) => {
        if (typeof value !== "string") return false;
        if (/^#(?:[\da-f]{3}|[\da-f]{4}|[\da-f]{6}|[\da-f]{8})$/i.test(value)) return true;
        const match = value.match(/^(rgb|rgba|hsl|hsla)\(([^()]*)\)$/i);
        if (!match) return false;
        const components = match[2].split(",");
        const functionName = match[1].toLowerCase();
        const hasAlpha = functionName.endsWith("a");
        return components.length === (hasAlpha ? 4 : 3)
          && components.every((component) => /^[+-]?(?:\d+(?:\.\d+)?|\.\d+)%?$/.test(component.trim()));
      };
      const colors = Object.fromEntries(
        Object.entries(defaultColors).map(([key, fallback]) => [
          key,
          isSafeColor(settings.colors?.[key]) ? settings.colors[key] : fallback,
        ]),
      );
      const requestedSpeed = Number(settings.speed_seconds);
      const speed = Number.isFinite(requestedSpeed) && requestedSpeed >= 10 && requestedSpeed <= 180
        ? requestedSpeed
        : 55;
      section.hidden = false;
      section.style.setProperty("--neen-news-background", colors.background);
      section.style.setProperty("--neen-news-text", colors.text);
      section.style.setProperty("--neen-news-sender", colors.sender);
      section.style.setProperty("--neen-news-separator", colors.separator);
      section.style.setProperty("--neen-news-glow", colors.glow);
      section.style.setProperty("--neen-news-speed", `${speed}s`);
      if (settings.enabled) {
        section.hidden = false;
        renderTrack(data.messages);
      } else {
        section.hidden = true;
      }
    } catch (error) {
      section.hidden = false;
      viewport.hidden = false;
      track.replaceChildren();
      const group = document.createElement("div");
      group.className = "neen-news-ticker-group";
      const item = document.createElement("span");
      item.className = "neen-news-ticker-item";
      item.textContent = "NEEN NEWS: News ticker is temporarily unavailable.";
      group.append(item);
      track.append(group, group.cloneNode(true));
    }
  };

  toggle?.addEventListener("click", () => {
    const opening = panel.hidden;
    panel.hidden = !opening;
    toggle.setAttribute("aria-expanded", String(opening));
  });

  form?.addEventListener("submit", async (event) => {
    event.preventDefault();
    if (!form.reportValidity()) return;
    const data = Object.fromEntries(new FormData(form));
    status.textContent = "Sending…";
    try {
      const csrfResponse = await fetch("/api/auth/csrf", { credentials: "same-origin", cache: "no-store" });
      const csrfResult = await csrfResponse.json();
      const csrfToken = csrfResult.data?.csrf_token;
      if (!csrfResponse.ok || typeof csrfToken !== "string") throw new Error("Could not prepare secure submission.");

      const response = await fetch("/api/news-ticker/messages", {
        method: "POST",
        credentials: "same-origin",
        headers: {
          "Accept": "application/json",
          "Content-Type": "application/json",
          "X-CSRF-Token": csrfToken,
        },
        body: JSON.stringify(data),
      });
      const result = await response.json();
      if (!response.ok || result.success !== true) {
        throw new Error(result.errors?.[0]?.message || "The message could not be sent.");
      }
      form.reset();
      status.textContent = "Your message was received and is waiting for owner review.";
    } catch (error) {
      status.textContent = error instanceof Error ? error.message : "The message could not be sent.";
    }
  });

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", loadTicker, { once: true });
  } else {
    loadTicker();
  }
})();

