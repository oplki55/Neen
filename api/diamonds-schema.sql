CREATE TABLE IF NOT EXISTS diamond_packages (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(120) NOT NULL,
    diamond_amount BIGINT UNSIGNED NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_diamond_packages_active (is_active),
    CONSTRAINT chk_diamond_packages_amount CHECK (diamond_amount > 0),
    CONSTRAINT chk_diamond_packages_price CHECK (price > 0),
    CONSTRAINT fk_diamond_packages_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_diamond_packages_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS diamond_recharge_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_number CHAR(19) NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    package_id BIGINT UNSIGNED NOT NULL,
    package_name VARCHAR(120) NOT NULL,
    diamond_amount BIGINT UNSIGNED NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    player_id VARCHAR(20) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    order_status ENUM('pending', 'payment_verification', 'paid', 'processing', 'delivered', 'rejected', 'failed', 'refunded', 'cancelled') NOT NULL,
    payment_status ENUM('pending', 'verification', 'paid', 'rejected', 'failed', 'refunded') NOT NULL,
    delivery_status ENUM('not_started', 'processing', 'delivered', 'failed', 'refunded') NOT NULL,
    payment_reference VARCHAR(150) NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_diamond_recharge_order_number (order_number),
    UNIQUE KEY uq_diamond_recharge_user_idempotency (user_id, idempotency_key),
    KEY idx_diamond_recharge_user_created (user_id, id),
    KEY idx_diamond_recharge_status_created (order_status, id),
    KEY idx_diamond_recharge_player_id (player_id, id),
    CONSTRAINT fk_diamond_recharge_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_diamond_recharge_package FOREIGN KEY (package_id) REFERENCES diamond_packages (id) ON DELETE RESTRICT,
    CONSTRAINT chk_diamond_recharge_amount CHECK (diamond_amount > 0),
    CONSTRAINT chk_diamond_recharge_price CHECK (price > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS diamond_order_activity (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    order_id BIGINT UNSIGNED NOT NULL,
    actor_user_id BIGINT UNSIGNED NULL,
    activity_type VARCHAR(60) NOT NULL,
    from_order_status VARCHAR(30) NULL,
    to_order_status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    delivery_status VARCHAR(30) NOT NULL,
    admin_note VARCHAR(1000) NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_diamond_order_activity_order (order_id, id),
    CONSTRAINT fk_diamond_order_activity_order FOREIGN KEY (order_id) REFERENCES diamond_recharge_orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_diamond_order_activity_actor FOREIGN KEY (actor_user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
