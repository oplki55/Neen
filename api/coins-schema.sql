CREATE TABLE IF NOT EXISTS coin_packages (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    name VARCHAR(120) NOT NULL,
    coin_amount BIGINT UNSIGNED NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    KEY idx_coin_packages_active (is_active),
    CONSTRAINT chk_coin_packages_amount CHECK (coin_amount > 0),
    CONSTRAINT chk_coin_packages_price CHECK (price > 0),
    CONSTRAINT fk_coin_packages_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_coin_packages_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coin_payment_methods (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    code VARCHAR(60) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    instructions TEXT NULL,
    proof_required TINYINT(1) NOT NULL DEFAULT 1,
    is_active TINYINT(1) NOT NULL DEFAULT 0,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_coin_payment_methods_code (code),
    KEY idx_coin_payment_methods_active (is_active),
    CONSTRAINT fk_coin_payment_methods_created_by FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT fk_coin_payment_methods_updated_by FOREIGN KEY (updated_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coin_orders (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    user_id BIGINT UNSIGNED NOT NULL,
    package_id BIGINT UNSIGNED NOT NULL,
    package_name VARCHAR(120) NOT NULL,
    coin_amount BIGINT UNSIGNED NOT NULL,
    price DECIMAL(10,2) NOT NULL,
    currency_code CHAR(3) NOT NULL,
    payment_method_id BIGINT UNSIGNED NOT NULL,
    payment_method_code VARCHAR(60) NOT NULL,
    payment_method_name VARCHAR(120) NOT NULL,
    proof_required TINYINT(1) NOT NULL,
    status ENUM('awaiting_payment', 'pending_review', 'approved', 'rejected', 'cancelled') NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_coin_orders_user_idempotency (user_id, idempotency_key),
    KEY idx_coin_orders_user_created (user_id, created_at),
    KEY idx_coin_orders_status_created (status, created_at),
    CONSTRAINT fk_coin_orders_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_orders_package FOREIGN KEY (package_id) REFERENCES coin_packages (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_orders_payment_method FOREIGN KEY (payment_method_id) REFERENCES coin_payment_methods (id) ON DELETE RESTRICT,
    CONSTRAINT chk_coin_orders_amount CHECK (coin_amount > 0),
    CONSTRAINT chk_coin_orders_price CHECK (price > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coin_order_evidence (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    coin_order_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    payment_reference VARCHAR(150) NULL,
    proof_details TEXT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_coin_order_evidence_idempotency (user_id, idempotency_key),
    UNIQUE KEY uq_coin_order_evidence_order (coin_order_id),
    KEY idx_coin_order_evidence_order (coin_order_id, created_at),
    CONSTRAINT fk_coin_order_evidence_order FOREIGN KEY (coin_order_id) REFERENCES coin_orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_order_evidence_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coin_order_reviews (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    coin_order_id BIGINT UNSIGNED NOT NULL,
    reviewer_user_id BIGINT UNSIGNED NOT NULL,
    decision ENUM('approved', 'rejected') NOT NULL,
    reason VARCHAR(1000) NOT NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    ledger_entry_id BIGINT UNSIGNED NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_coin_order_reviews_order (coin_order_id),
    UNIQUE KEY uq_coin_order_reviews_reviewer_idempotency (reviewer_user_id, idempotency_key),
    CONSTRAINT fk_coin_order_reviews_order FOREIGN KEY (coin_order_id) REFERENCES coin_orders (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_order_reviews_reviewer FOREIGN KEY (reviewer_user_id) REFERENCES users (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS coin_ledger (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    wallet_id BIGINT UNSIGNED NOT NULL,
    user_id BIGINT UNSIGNED NOT NULL,
    operation_type ENUM('credit', 'debit', 'reversal') NOT NULL,
    source VARCHAR(60) NOT NULL,
    amount BIGINT UNSIGNED NOT NULL,
    balance_type ENUM('purchased', 'earned') NOT NULL,
    balance_before BIGINT UNSIGNED NOT NULL,
    balance_after BIGINT UNSIGNED NOT NULL,
    total_balance_before BIGINT UNSIGNED NOT NULL,
    total_balance_after BIGINT UNSIGNED NOT NULL,
    status ENUM('completed') NOT NULL DEFAULT 'completed',
    reference_type VARCHAR(80) NULL,
    reference_id BIGINT UNSIGNED NULL,
    idempotency_key VARCHAR(100) NOT NULL,
    reversal_of_id BIGINT UNSIGNED NULL,
    note VARCHAR(1000) NULL,
    created_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    UNIQUE KEY uq_coin_ledger_user_idempotency (user_id, idempotency_key),
    UNIQUE KEY uq_coin_ledger_reversal_of (reversal_of_id),
    KEY idx_coin_ledger_user_created (user_id, created_at, id),
    KEY idx_coin_ledger_wallet_created (wallet_id, created_at, id),
    KEY idx_coin_ledger_reference (reference_type, reference_id),
    CONSTRAINT chk_coin_ledger_amount CHECK (amount > 0),
    CONSTRAINT fk_coin_ledger_wallet FOREIGN KEY (wallet_id) REFERENCES wallets (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_ledger_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_coin_ledger_reversal FOREIGN KEY (reversal_of_id) REFERENCES coin_ledger (id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
